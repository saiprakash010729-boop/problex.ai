/**
 * PROBLEX AI - PDF GENERATION UTILITY
 * Generates formatted downloadable PDF documents for AI answers,
 * Short Notes, and Revision Guides.
 */

// Escape text for raw PDF stream
function escapePdfText(text) {
  if (!text) return '';
  return text
    .replace(/\\/g, '\\\\')
    .replace(/\(/g, '\\(')
    .replace(/\)/g, '\\)')
    .replace(/[^\x20-\x7E\n]/g, ' '); // Clean non-ASCII for pure PDF-1.4 compatibility
}

// Generate raw PDF 1.4 binary string
export function buildRawPdf({ title, topic, studentName, course, academicLevel, sections = [] }) {
  const dateStr = new Date().toLocaleDateString('en-US', { month: 'long', day: 'numeric', year: 'numeric' });
  
  // Format content lines
  const lines = [
    `PROBLEX AI - ACADEMIC STUDY DOCUMENT`,
    `Tagline: Learn Smarter. Solve Better. Build Your Future.`,
    `--------------------------------------------------------------------------------`,
    `DOCUMENT TITLE : ${title.toUpperCase()}`,
    `TOPIC          : ${topic}`,
    `STUDENT        : ${studentName || 'Student'} (${course || 'B.Tech'} - ${academicLevel || 'Current Level'})`,
    `DATE           : ${dateStr}`,
    `PLATFORM       : Problex AI - Bilingual Learning Platform`,
    `--------------------------------------------------------------------------------`,
    ``
  ];

  sections.forEach(sec => {
    lines.push(`[SECTION: ${sec.heading.toUpperCase()}]`);
    lines.push(sec.content || '');
    lines.push(``);
  });

  lines.push(`--------------------------------------------------------------------------------`);
  lines.push(`Generated by Problex AI - Verified for Semester Exams & Competitive Aspirants`);

  // Wrap text into formatted PDF stream
  let streamContent = `BT\n/F1 10 Tf\n12 TL\n50 780 Td\n`;
  
  lines.forEach((line) => {
    // Word wrap roughly 85 characters
    const chunks = line.match(/.{1,85}(\s|$)/g) || [line];
    chunks.forEach(chunk => {
      const cleanChunk = escapePdfText(chunk.trim());
      if (cleanChunk) {
        streamContent += `(${cleanChunk}) '\n`;
      } else {
        streamContent += `() '\n`;
      }
    });
  });

  streamContent += `ET`;

  const streamLength = streamContent.length;

  const pdfBody = `%PDF-1.4
1 0 obj
<< /Type /Catalog /Pages 2 0 R >>
endobj
2 0 obj
<< /Type /Pages /Kids [3 0 R] /Count 1 >>
endobj
3 0 obj
<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] /Contents 4 0 R /Resources << /Font << /F1 5 0 R >> >> >>
endobj
4 0 obj
<< /Length ${streamLength} >>
stream
${streamContent}
endstream
endobj
5 0 obj
<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>
endobj
xref
0 6
0000000000 65535 f 
0000000010 00000 n 
0000000060 00000 n 
0000000118 00000 n 
0000000244 00000 n 
0000000300 00000 n 
trailer
<< /Size 6 /Root 1 0 R >>
startxref
380
%%EOF`;

  return pdfBody;
}

// Download directly as a .pdf file
export function downloadPdfDocument({ title, topic, studentName, course, academicLevel, sections = [], rawText }) {
  // If sections not provided, break rawText into sections
  let formattedSections = sections;
  if (!formattedSections.length && rawText) {
    const rawParagraphs = rawText.split('\n\n').filter(p => p.trim());
    formattedSections = rawParagraphs.map((p, idx) => ({
      heading: idx === 0 ? "Overview & Explanation" : `Key Notes - Part ${idx + 1}`,
      content: p.replace(/[#*`]/g, '').trim()
    }));
  }

  const pdfData = buildRawPdf({
    title: title || "Academic Study Note",
    topic: topic || "Course Topic",
    studentName: studentName || "Problex Student",
    course: course || "Academic Studies",
    academicLevel: academicLevel || "General",
    sections: formattedSections
  });

  const blob = new Blob([pdfData], { type: 'application/pdf' });
  const filename = `Problex_AI_${(topic || title || 'Notes').replace(/[^a-zA-Z0-9]/g, '_').substring(0, 30)}.pdf`;

  const link = document.createElement('a');
  link.href = URL.createObjectURL(blob);
  link.download = filename;
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(link.href);
}

// Print / View formatted document preview
